#!/usr/bin/env node
/**
 * Builds the Worker and the browser bundle it serves.
 *
 * Two stages, in order, because the second embeds the first.
 *
 *   1. the browser entry is bundled and hashed;
 *   2. the Worker is bundled with that output inlined as text.
 *
 * ## Why the client is inlined rather than uploaded as an asset
 *
 * A Worker can serve static assets, but that is a second deployment surface
 * with its own configuration and its own way to be stale. The bundle is small
 * and the Worker already returns bytes for a living, so it ships inside the
 * Worker and is served from one place that cannot disagree with itself.
 *
 * The path carries the content hash, so `immutable` caching is honest: a
 * different build is a different URL, and no browser can hold a stale bundle.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'src');
const DIST = join(HERE, 'dist');
const ASSETS = join(HERE, 'assets');

mkdirSync(DIST, { recursive: true });

// ── 0. the images ───────────────────────────────────────────────────────────
//
// The variants themselves are produced by `scripts/build-hero-image.mjs`, which
// needs `avifenc` and `cwebp`; this stage only reads the bytes that step already
// committed. So a machine with Node and nothing else can still build and deploy.
//
// They are embedded rather than uploaded as static assets for the same reason
// the client bundle is: one deployment surface that cannot disagree with itself.
// The hash is over the bytes, so `immutable` is honest, and a few hundred kb of
// pictures in a Worker is not the thing that will make it big.

const hero = JSON.parse(readFileSync(join(ASSETS, 'hero.json'), 'utf8'));

/** @type {{path:string,type:string,base64:string}[]} */
const images = [];
for (const variant of hero.variants) {
  const formats = [
    ['avif', 'image/avif'],
    ['webp', 'image/webp'],
    ...(variant.png > 0 ? [['png', 'image/png']] : []),
  ];
  for (const [extension, type] of formats) {
    const bytes = readFileSync(join(ASSETS, `hero-${variant.width}.${extension}`));
    const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    images.push({
      key: `hero-${variant.width}.${extension}`,
      path: `/assets/hero-${variant.width}.${digest}.${extension}`,
      type,
      width: variant.width,
      height: variant.height,
      base64: bytes.toString('base64'),
    });
  }
}

// The link-preview card comes from the brand kit, not from this directory, so there
// is one copy of the identity and `pnpm brand:check` is what guards it. It rides in
// the same hashed-image table as the hero: crawlers cache an image by URL, and a new
// card is a new URL, so a changed card can never be served stale to a preview.
const BRAND = join(HERE, '..', '..', 'brand');
const ogBytes = readFileSync(join(BRAND, 'social', 'conduit-og-1200x630.png'));
const ogDigest = createHash('sha256').update(ogBytes).digest('hex').slice(0, 12);
images.push({
  key: 'brand-og.png',
  path: `/assets/conduit-og.${ogDigest}.png`,
  type: 'image/png',
  width: ogBytes.readUInt32BE(16),
  height: ogBytes.readUInt32BE(20),
  base64: ogBytes.toString('base64'),
});

writeFileSync(
  join(SRC, 'image-manifest.ts'),
  `// Generated by build.mjs. Do not edit; the hashes change with the bytes.\n` +
    `export interface ImageAsset {\n` +
    `  readonly path: string;\n` +
    `  readonly type: string;\n` +
    `  readonly width: number;\n` +
    `  readonly height: number;\n` +
    `  readonly base64: string;\n` +
    `}\n\n` +
    `/** The hero artwork's intrinsic size, after the crop in hero.json. */\n` +
    `export const HERO_INTRINSIC = { width: ${hero.intrinsic[0]}, height: ${hero.intrinsic[1]} } as const;\n\n` +
    `export const IMAGES: Readonly<Record<string, ImageAsset>> = Object.freeze({\n` +
    images
      .map(
        (image) =>
          `  '${image.key}': { path: '${image.path}', type: '${image.type}', ` +
          `width: ${image.width}, height: ${image.height}, base64: '${image.base64}' },`,
      )
      .join('\n') +
    `\n});\n`,
);

// ── 0b. the brand ───────────────────────────────────────────────────────────
//
// Two things from `brand/` that the Worker needs and the hashed-image table does not
// cover.
//
// Root files. Browsers ask for /favicon.ico and /apple-touch-icon.png by name without
// being told to, and the web manifest names its icons by root path, so these have to
// live at fixed URLs. They cannot be immutable: the name stays when the bytes change.
//
// The lockup. The sidebar and the landing header and footer draw it inline, which keeps it one
// request, lets CSS size it, and means it cannot fail to load. It is rewritten here
// from the master rather than copied into a template, so the page can only ever show
// what `brand/source/` says.

const ROOT_FILES = [
  ['/favicon.ico', 'favicon/favicon.ico', 'image/x-icon'],
  ['/favicon.svg', 'favicon/favicon.svg', 'image/svg+xml'],
  ['/apple-touch-icon.png', 'favicon/apple-touch-icon.png', 'image/png'],
  ['/icon-192.png', 'favicon/icon-192.png', 'image/png'],
  ['/icon-512.png', 'favicon/icon-512.png', 'image/png'],
  ['/icon-maskable-512.png', 'favicon/icon-maskable-512.png', 'image/png'],
  ['/site.webmanifest', 'favicon/site.webmanifest', 'application/manifest+json'],
];

/** The master with its intrinsic size and accessible name removed, ready to sit in a link. */
function inlineLockup(svg) {
  return svg
    .replace(' xmlns="http://www.w3.org/2000/svg"', '')
    .replace(/ width="[^"]*" height="[^"]*"/, '')
    .replace(' role="img"', ' aria-hidden="true" focusable="false"')
    .replace(/<title>[^<]*<\/title>/, '')
    .replace('<svg ', '<svg class="lockup" ')
    .trim();
}

const lockup = inlineLockup(
  readFileSync(join(BRAND, 'source', 'conduit-lockup-horizontal.svg'), 'utf8'),
);
if (!lockup.startsWith('<svg class="lockup" viewBox=') || lockup.includes('<text')) {
  throw new Error('the lockup master no longer has the shape build.mjs expects');
}

writeFileSync(
  join(SRC, 'brand-manifest.ts'),
  `// Generated by build.mjs from brand/. Do not edit; change the kit and rebuild.\n` +
    `export interface BrandFile {\n` +
    `  readonly type: string;\n` +
    `  readonly base64: string;\n` +
    `}\n\n` +
    `/** Served at a fixed root path, because browsers and the manifest ask for them by name. */\n` +
    `export const BRAND_ROOT_FILES: Readonly<Record<string, BrandFile>> = Object.freeze({\n` +
    ROOT_FILES.map(
      ([path, file, type]) =>
        `  '${path}': { type: '${type}', base64: '${readFileSync(join(BRAND, file)).toString('base64')}' },`,
    ).join('\n') +
    `\n});\n\n` +
    `/** The horizontal lockup as inline SVG, sized by CSS. */\n` +
    `export const LOCKUP_INLINE = ${JSON.stringify(lockup)};\n`,
);

// ── 1. the browser ──────────────────────────────────────────────────────────

const client = await esbuild.build({
  entryPoints: [join(SRC, 'client', 'main.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  sourcemap: false,
  write: false,
  legalComments: 'none',
});

const clientCode = client.outputFiles[0].text;
const hash = createHash('sha256').update(clientCode).digest('hex').slice(0, 12);
const clientPath = `/assets/client.${hash}.js`;

// Written into `src` because the Worker imports it; it is generated output and
// is gitignored rather than committed.
writeFileSync(join(SRC, 'client.bundle.js.txt'), clientCode);
writeFileSync(
  join(SRC, 'client-manifest.ts'),
  `// Generated by build.mjs. Do not edit; the hash changes with the bundle.\n` +
    `export const CLIENT_PATH = '${clientPath}';\n`,
);

// ── 2. the Worker ───────────────────────────────────────────────────────────

await esbuild.build({
  entryPoints: [join(SRC, 'worker.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  conditions: ['workerd', 'worker', 'import', 'module', 'default'],
  target: 'es2022',
  external: ['node:*', 'cloudflare:*'],
  loader: { '.txt': 'text' },
  outfile: join(DIST, 'worker.bundle.js'),
});

const kib = (bytes) => `${(bytes / 1024).toFixed(1)}kb`;
const imageBytes = images.reduce((total, image) => total + (image.base64.length * 3) / 4, 0);
console.log(`images ${images.length} files  ${kib(imageBytes)}`);
console.log(`brand ${ROOT_FILES.length} root files, lockup ${lockup.length} bytes inline`);
console.log(`client ${clientPath}  ${kib(Buffer.byteLength(clientCode))}`);
console.log(`worker dist/worker.bundle.js`);
