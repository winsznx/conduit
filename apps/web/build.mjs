#!/usr/bin/env node
/**
 * Builds the Worker and the browser bundle it serves.
 *
 * Two stages, in order, because the second embeds the first.
 *
 *   1. the browser entry is bundled and hashed;
 *   2. the Worker is bundled with that output inlined as text.
 *
 * ## Why the client is inlined rather than uploaded as an asset
 *
 * A Worker can serve static assets, but that is a second deployment surface
 * with its own configuration and its own way to be stale. The bundle is small
 * and the Worker already returns bytes for a living, so it ships inside the
 * Worker and is served from one place that cannot disagree with itself.
 *
 * The path carries the content hash, so `immutable` caching is honest: a
 * different build is a different URL, and no browser can hold a stale bundle.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'src');
const DIST = join(HERE, 'dist');
const ASSETS = join(HERE, 'assets');

mkdirSync(DIST, { recursive: true });

// ── 0. the images ───────────────────────────────────────────────────────────
//
// The variants themselves are produced by `scripts/build-hero-image.mjs`, which
// needs `avifenc` and `cwebp`; this stage only reads the bytes that step already
// committed. So a machine with Node and nothing else can still build and deploy.
//
// They are embedded rather than uploaded as static assets for the same reason
// the client bundle is: one deployment surface that cannot disagree with itself.
// The hash is over the bytes, so `immutable` is honest, and 187kb of pictures in
// a Worker is not the thing that will make it big.

const hero = JSON.parse(readFileSync(join(ASSETS, 'hero.json'), 'utf8'));

/** @type {{path:string,type:string,base64:string}[]} */
const images = [];
for (const variant of hero.variants) {
  const formats = [
    ['avif', 'image/avif'],
    ['webp', 'image/webp'],
    ...(variant.png > 0 ? [['png', 'image/png']] : []),
  ];
  for (const [extension, type] of formats) {
    const bytes = readFileSync(join(ASSETS, `hero-${variant.width}.${extension}`));
    const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    images.push({
      key: `hero-${variant.width}.${extension}`,
      path: `/assets/hero-${variant.width}.${digest}.${extension}`,
      type,
      width: variant.width,
      height: variant.height,
      base64: bytes.toString('base64'),
    });
  }
}

writeFileSync(
  join(SRC, 'image-manifest.ts'),
  `// Generated by build.mjs. Do not edit; the hashes change with the bytes.\n` +
    `export interface ImageAsset {\n` +
    `  readonly path: string;\n` +
    `  readonly type: string;\n` +
    `  readonly width: number;\n` +
    `  readonly height: number;\n` +
    `  readonly base64: string;\n` +
    `}\n\n` +
    `/** The hero artwork's intrinsic size, after the crop in hero.json. */\n` +
    `export const HERO_INTRINSIC = { width: ${hero.intrinsic[0]}, height: ${hero.intrinsic[1]} } as const;\n\n` +
    `export const IMAGES: Readonly<Record<string, ImageAsset>> = Object.freeze({\n` +
    images
      .map(
        (image) =>
          `  '${image.key}': { path: '${image.path}', type: '${image.type}', ` +
          `width: ${image.width}, height: ${image.height}, base64: '${image.base64}' },`,
      )
      .join('\n') +
    `\n});\n`,
);

// ── 1. the browser ──────────────────────────────────────────────────────────

const client = await esbuild.build({
  entryPoints: [join(SRC, 'client', 'main.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  sourcemap: false,
  write: false,
  legalComments: 'none',
});

const clientCode = client.outputFiles[0].text;
const hash = createHash('sha256').update(clientCode).digest('hex').slice(0, 12);
const clientPath = `/assets/client.${hash}.js`;

// Written into `src` because the Worker imports it; it is generated output and
// is gitignored rather than committed.
writeFileSync(join(SRC, 'client.bundle.js.txt'), clientCode);
writeFileSync(
  join(SRC, 'client-manifest.ts'),
  `// Generated by build.mjs. Do not edit; the hash changes with the bundle.\n` +
    `export const CLIENT_PATH = '${clientPath}';\n`,
);

// ── 2. the Worker ───────────────────────────────────────────────────────────

await esbuild.build({
  entryPoints: [join(SRC, 'worker.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  conditions: ['workerd', 'worker', 'import', 'module', 'default'],
  target: 'es2022',
  external: ['node:*', 'cloudflare:*'],
  loader: { '.txt': 'text' },
  outfile: join(DIST, 'worker.bundle.js'),
});

const kib = (bytes) => `${(bytes / 1024).toFixed(1)}kb`;
const imageBytes = images.reduce((total, image) => total + (image.base64.length * 3) / 4, 0);
console.log(`images ${images.length} variants  ${kib(imageBytes)}`);
console.log(`client ${clientPath}  ${kib(Buffer.byteLength(clientCode))}`);
console.log(`worker dist/worker.bundle.js`);
